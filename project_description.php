    <div>
        <h3>So_long - Projet C (École 42)</h3>
        <h4>Création d'un jeu 2D avec MiniLibX</h4>
        <p><strong>Présentation du projet :</strong> Le projet <em>So_long</em> est une introduction au développement de jeux 2D en langage C[cite: 19, 22]. Il combine la rigueur algorithmique, la manipulation de fichiers de configuration de cartes et l'utilisation d'une bibliothèque graphique pour gérer une fenêtre, des textures, des sprites et des événements clavier[cite: 22, 24, 25].</p>
        <h4>Règles du jeu :</h4>
        <ul>
            <li><strong>Objectif principal :</strong> Le joueur contrôle un personnage et doit collecter tous les éléments de collection (collectibles) présents sur la carte avant de s'échapper par la sortie avec un minimum de déplacements[cite: 24, 25].</li>
            <li><strong>Contraintes de déplacement :</strong> Le joueur peut se déplacer dans quatre directions (haut, bas, gauche, droite) à l'aide des touches W, A, S, D[cite: 24, 25].</li>
            <li><strong>Obstacles :</strong> Il est strictement impossible de traverser les murs, qui délimitent et entourent obligatoirement l'ensemble de la carte[cite: 25].</li>
            <li><strong>Compteur de pas :</strong> À chaque mouvement effectué, le nombre total de déplacements est affiché et mis à jour en temps réel dans le terminal[cite: 25].</li>
        </ul>
        <h4>Fonctionnalités principales :</h4>
        <ul>
            <li><strong>Parsing de cartes (.ber) :</strong> Analyse, lecture et validation rigoureuse des fichiers de niveaux définissant l'environnement à l'aide de caractères spécifiques : murs (<code>1</code>), espaces vides (<code>0</code>), collectibles (<code>C</code>), position de départ (<code>P</code>) et sortie (<code>E</code>)[cite: 25].</li>
            <li><strong>Moteur graphique & Textures :</strong> Affichage d'une grille 2D texturée à l'aide de la MiniLibX, garantissant une gestion fluide de la fenêtre[cite: 24, 25].</li>
            <li><strong>Gestion des événements :</strong> Capture instantanée des entrées clavier pour le mouvement ou la fermeture propre du jeu via la touche ESC ou le clic sur la croix rouge[cite: 25].</li>
        </ul>
        <h4>Implémentation technique & Notions clés :</h4>
        <ul>
            <li><strong>Gestion de la mémoire :</strong> Absence totale de fuites mémoire (leaks) et traitement sécurisé des erreurs de configuration de cartes avec l'affichage d'un message explicite[cite: 23, 26].</li>
            <li><strong>Version Bonus :</strong> Implémentation d'animations de sprites, de pièges causant la défaite en cas de contact, et affichage direct du compteur de pas à l'écran[cite: 27].</li>
        </ul>
