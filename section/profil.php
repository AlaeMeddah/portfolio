            <h3>Mon parcours</h3>

            <p>
                Mon parcours est avant tout celui d'une curiosité qui m'a
                progressivement conduit vers le développement informatique.
            </p>

            <p>
                Après un baccalauréat scientifique S-SVT, j'ai exploré
                différentes voies avant de rejoindre un DUT Mesures Physiques.
                C'est au cours de cette formation que j'ai découvert la
                programmation, une discipline qui m'a immédiatement passionné
                par sa capacité à mêler logique, créativité et résolution
                de problèmes.
            </p>

            <p>
                Cette découverte m'a conduit chez Siemens, à Haguenau, où
                j'ai effectué mon stage de fin d'études avant de poursuivre
                en CDD de huit mois. J'y ai participé à la refonte d'un
                logiciel de test de transducteurs à ultrasons, en développant
                une nouvelle solution en Python pour remplacer un outil
                devenu incompatible avec les équipements de nouvelle
                génération. Cette expérience concrète en R&D a confirmé
                mon envie de poursuivre dans le développement logiciel.
            </p>

            <p>
                J'ai ensuite intégré l'école 42 au Havre afin d'approfondir
                mes connaissances. Pendant un an et demi, j'y ai développé
                mon autonomie, ma rigueur et mes compétences en programmation,
                notamment en C et en C++. Même si mon parcours au sein de
                l'école s'est arrêté avant son terme, cette expérience m'a
                permis de gagner en maturité et de mieux définir mes objectifs.
            </p>

            <p>
                Aujourd'hui, je poursuis cette aventure à Epitech, dans un
                environnement qui partage mon goût pour l'apprentissage
                par la pratique et les projets concrets, avec une approche
                qui correspond davantage à mes valeurs. J'y continue
                d'explorer de nouvelles technologies et de développer
                mes compétences à travers des projets variés.
            </p>

            <p>
                Mon parcours m'a appris à m'adapter, à apprendre par moi-même
                et à considérer chaque expérience comme une occasion de
                progresser. Je suis convaincu que la diversité de mes
                expériences constitue une véritable force : elle me permet
                d'aborder les problématiques avec recul, curiosité et
                polyvalence.
            </p>

            <p>
                Et ce n'est que le début : je compte bien continuer à
                apprendre, expérimenter et enrichir mon éventail
                de compétences.
            </p>
